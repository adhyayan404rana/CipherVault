const assert=require('node:assert/strict');
const {analyse,radar}=require('../hosted/traffic.js');
const header='No.,Time,Source,Destination,Protocol,Length,Info\r\n';
const result=analyse('\uFEFF'+header+'1,0,::1,::2,TCP,60,"hello, ""world"""\r\n2,2,::2,::1,TLSv1.3,100,"line\nbreak"');
assert.equal(result.bytes,160);assert.equal(result.duration,2);
assert.deepEqual(result.timeline.map(b=>b.packets),[1,0,1]);
assert.equal(result.packets[0].info,'hello, "world"');
assert.equal(result.endpoints[0].sent_bytes+result.endpoints[0].received_bytes,160);
const exposure=radar(result);
assert.equal(exposure.signals[0].value,'2 visible addresses');
assert.equal(exposure.bursts.length,2);
assert.equal(exposure.signals[2].value,'160 frame bytes');
assert.equal(exposure.visibleRequests.length,0);
assert.equal(analyse(header+'1,0,a,b,TCP,0,empty').duration,0);
assert.throws(()=>analyse(header+'1,12:00:00,a,b,TCP,1,test'),/numeric/);
assert.throws(()=>analyse(header+'1,0,a,b,TCP,-1,test'),/Invalid packet/);
assert.throws(()=>analyse(header+'1,0,a,b,TCP,1,"unfinished'),/unfinished/);
assert.throws(()=>analyse(header+'1,0,a,b,TCP,1'),/columns/);
assert.throws(()=>analyse('Time,Length\n0,1'),/default Wireshark/);
assert.throws(()=>analyse(header),/no packets/);
console.log('Traffic analysis parser and aggregation checks passed.');
